export interface AxIdea {
  id: string;
  stage: StageKey | "전 구간" | "확장";
  title: string;
  /** 지금은 어떻게 하고 있나 */
  asIs: string;
  /** 무엇이 바뀌나 */
  toBe: string;
  /**
   * 쓰는 수단. 한 지점이 여러 층위에 걸치기도 한다.
   * 셀렉이 그렇다 — 연산으로 걸러서 LLM에 가는 장수를 줄이는 것이 설계의 핵심이라
   * 한 층위로 뭉뚱그리면 근거가 무너진다.
   */
  tiers: Tier[];
  /** 왜 이 수단인가 */
  why: string;
  /** 이 지점에서 그 층위가 구체적으로 무엇인지 */
  means: Partial<Record<Tier, string>>;
  /** 화면 주석에 뜨는 짧은 문구 */
  note: string;
}

