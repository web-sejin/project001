/**
 * 이 지점이 AI를 쓰는가, 자동화인가.
 *
 * 과제가 "AI 또는 자동화"라고 물었으므로 둘을 섞어 보여주면 안 된다.
 * 전용 모델도 학습 모델이라 AI로 본다. 순수 연산과 규칙만 자동화다.
 */
export type AxKind = "AI" | "자동화";

export function axKind(idea: AxIdea): AxKind {
  return idea.tiers.some((t) => t === "LLM" || t === "LLM 비전" || t === "전용 모델")
    ? "AI"
    : "자동화";
}

export function axIdea(id: string): AxIdea | undefined {
  return AX_IDEAS.find((i) => i.id === id);
}
